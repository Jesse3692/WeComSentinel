const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fs = require('node:fs');
const assert = require('node:assert/strict');

(async () => {
  const password = fs.readFileSync('.env','utf8').match(/^DEMO_PASSWORD=(.+)$/m)?.[1].trim();
  if (!password) throw new Error('Demo configuration is required');
  fs.mkdirSync('data/screenshots', {recursive:true});
  const browser = await chromium.launch({headless:true, ...(process.env.BROWSER_CHANNEL ? {channel:process.env.BROWSER_CHANNEL} : {})});
  const page = await browser.newPage({viewport:{width:1440,height:1050}});
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://localhost:8000/');
  await page.getByLabel('演示密码').fill(password);
  await page.getByRole('button',{name:'进入演示',exact:true}).click();
  await page.getByText('客户关系总览',{exact:true}).waitFor();
  await page.locator('.metric').first().waitFor();
  assert.equal(await page.locator('.metric').count(),4);
  await page.screenshot({path:'data/screenshots/dashboard-desktop.png',fullPage:true});
  await page.locator('.metric').first().click();
  await page.locator('.event-row').first().waitFor();
  await page.locator('.event-row').first().click();
  await page.getByRole('dialog').waitFor();
  await page.getByRole('button',{name:'关闭',exact:true}).click();
  await page.locator('.admin-nav').click();
  await page.getByRole('heading',{name:'接入主体',exact:true}).waitFor();
  await page.locator('.admin-item').nth(3).waitFor();
  assert.ok(await page.locator('.admin-item').count()>=4);
  await page.locator('.sidebar nav button').first().click();
  await page.setViewportSize({width:390,height:844});
  await page.locator('.metric').first().waitFor();
  await page.screenshot({path:'data/screenshots/dashboard-mobile.png',fullPage:true});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.locator('.mobile-nav button').nth(3).click();
  await page.locator('.event-row').first().waitFor();
  await page.screenshot({path:'data/screenshots/groups-mobile.png',fullPage:true});
  await page.locator('.mobile-nav button').nth(4).click();
  await page.locator('.profile').getByRole('button',{name:'退出登录',exact:true}).click();
  await page.getByLabel('演示角色').selectOption('user');
  await page.getByLabel('演示密码').fill(password);
  await page.getByRole('button',{name:'进入演示',exact:true}).click();
  await page.locator('.metric').first().waitFor();
  assert.equal(await page.locator('.filters select option').count(),2);
  const forbidden = await page.evaluate(async()=> (await fetch('/api/v1/admin/users')).status);
  assert.equal(forbidden,403);
  assert.deepEqual(errors,[]);
  console.log('Browser smoke passed: desktop, mobile, detail, admin, logout and tenant isolation');
  await browser.close();
})().catch(error=>{console.error(error);process.exit(1)});
